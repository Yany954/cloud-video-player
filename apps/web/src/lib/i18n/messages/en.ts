/** The shape every language must have: same keys; texts stay texts, functions keep their arguments. */
type Shape<T> = {
  [K in keyof T]: T[K] extends (...args: infer A) => string
    ? (...args: A) => string
    : T[K] extends string
      ? string
      : Shape<T[K]>;
};
export type Messages = Shape<typeof en>;
